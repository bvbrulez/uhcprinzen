create or replace function public.log_transaction_audit()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor_email text := coalesce(auth.jwt() ->> 'email', 'Unbekannt');
  audit_action text;
begin
  if tg_op = 'INSERT' then
    new.created_by := auth.uid();
    new.created_by_email := actor_email;
    insert into public.transaction_audit_log
      (transaction_id, action, actor_id, actor_email, new_data)
    values
      (new.id, 'created', auth.uid(), actor_email, to_jsonb(new));
    return new;
  end if;

  new.updated_at := now();
  new.updated_by := auth.uid();
  new.updated_by_email := actor_email;
  if new.deleted_at is not null and old.deleted_at is null then
    new.deleted_by := auth.uid();
    new.deleted_by_email := actor_email;
    audit_action := 'deleted';
  elsif old.deleted_at is not null and new.deleted_at is null then
    new.deleted_by := null;
    new.deleted_by_email := null;
    audit_action := 'restored';
  else
    audit_action := 'updated';
  end if;

  insert into public.transaction_audit_log
    (transaction_id, action, actor_id, actor_email, old_data, new_data)
  values
    (new.id, audit_action, auth.uid(), actor_email, to_jsonb(old), to_jsonb(new));
  return new;
end;
$$;

drop trigger if exists transactions_audit on public.transactions;
drop trigger if exists transactions_audit_log on public.transactions;
create trigger transactions_audit_log
before insert or update on public.transactions
for each row execute function public.log_transaction_audit();

create or replace function public.create_due_recurring_transactions()
returns integer
language plpgsql
security invoker
set search_path = ''
as $$
declare
  schedule public.recurring_transactions%rowtype;
  occurrence_date date;
  following_month date;
  last_day integer;
  next_year integer;
  next_month integer;
  inserted_count integer := 0;
  created_id bigint;
begin
  if not public.is_finance_admin() then
    raise exception 'Nur Administratoren dürfen Wiederholungsbuchungen erzeugen.';
  end if;

  for schedule in
    select * from public.recurring_transactions
    where active and next_date <= current_date
      and (end_date is null or next_date <= end_date)
    order by next_date, id
    for update
  loop
    occurrence_date := schedule.next_date;
    while occurrence_date <= current_date
      and (schedule.end_date is null or occurrence_date <= schedule.end_date)
    loop
      insert into public.transactions
        (type, account, description, amount, transaction_date, category,
         recurring_transaction_id, recurring_for)
      values
        (schedule.type, schedule.account, schedule.description, schedule.amount,
         occurrence_date, schedule.category, schedule.id, occurrence_date)
      on conflict (recurring_transaction_id, recurring_for)
        where recurring_transaction_id is not null
        do nothing
      returning id into created_id;

      if created_id is not null then
        inserted_count := inserted_count + 1;
      end if;
      created_id := null;
      if inserted_count > 500 then
        raise exception 'Mehr als 500 Buchungen sind fällig. Bitte erzeuge sie in kleineren Schritten.';
      end if;

      if schedule.interval_type = 'weekly' then
        occurrence_date := occurrence_date + 7;
      elsif schedule.interval_type = 'yearly' then
        next_year := extract(year from occurrence_date)::integer + 1;
        next_month := extract(month from occurrence_date)::integer;
        last_day := extract(day from (
          make_date(next_year, next_month, 1) + interval '1 month - 1 day'
        ))::integer;
        occurrence_date := make_date(next_year, next_month, least(schedule.day_of_month, last_day));
      else
        following_month := (date_trunc('month', occurrence_date) + interval '1 month')::date;
        last_day := extract(day from (following_month + interval '1 month - 1 day'))::integer;
        occurrence_date := make_date(
          extract(year from following_month)::integer,
          extract(month from following_month)::integer,
          least(schedule.day_of_month, last_day)
        );
      end if;
    end loop;

    update public.recurring_transactions
    set next_date = occurrence_date,
        active = end_date is null or occurrence_date <= end_date
    where id = schedule.id;
  end loop;

  return inserted_count;
end;
$$;
grant execute on function public.create_due_recurring_transactions() to authenticated;

